export function translate(source, locale = 'zh-Hant') {
  if (locale !== 'en') return source;
  const text = source.trim();
  let value = english[text];
  let match;
  if (value === undefined) {
    if ((match = text.match(/^(\d+) 分，共 10 分$/))) value = `${match[1]} out of 10`;
    else if ((match = text.match(/^共 (\d+) 分鐘$/))) value = `${match[1]} min total`;
    else if ((match = text.match(/^(\d+) 分鐘$/))) value = `${match[1]} min`;
    else if ((match = text.match(/^第 (\d+) \/ (\d+) 步 · (.+)$/))) value = `Step ${match[1]} / ${match[2]} · ${translate(match[3], 'en')}`;
    else if ((match = text.match(/^(.+)，現在呢？$/))) value = `${translate(match[1], 'en')} — how is it now?`;
    else if ((match = text.match(/^接下來：(.+)$/))) value = `Next: ${translate(match[1], 'en')}`;
    else if ((match = text.match(/^已選擇(.+)$/))) value = `Selected: ${translate(match[1], 'en')}`;
    else if ((match = text.match(/^開始第 (\d+) 步：(.+)$/))) value = `Step ${match[1]}: ${translate(match[2], 'en')}`;
    else if ((match = text.match(/^不必一定變好，只要誠實地感受現在。恢復前的能量：(\d+) \/ 10。$/))) value = `You don’t have to feel better. Just notice how you feel now. Energy before resting: ${match[1]} / 10.`;
    else if ((match = text.match(/^(依照你選擇的|這次先從)「(.+)」開始。(照顧到：(.+)。|今天先留一點單純的休息時間。)時間只是提案，舒服最重要。$/))) value = `${match[1] === '依照你選擇的' ? 'Your choice' : 'Start with'}: ${translate(match[2], 'en')}. ${match[4] ? `You selected: ${match[4].split('、').map(n => translate(n, 'en')).join(', ')}. ` : 'Make a little room for a simple break today. '}The timing is a suggestion. Your comfort comes first.`;
    else value = text;
  }
  return source.replace(text, value);
}

export function installLocalization(root = document) {
  let locale = 'zh-Hant';
  const textMemory = new WeakMap();
  const attributeMemory = new WeakMap();
  const attributes = ['title', 'aria-label', 'aria-valuetext'];
  const observer = new MutationObserver(apply);
  function apply() {
    observer.disconnect();
    const walker = document.createTreeWalker(root.documentElement, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest('script, style, [data-no-translate]')) continue;
      const saved = textMemory.get(node);
      const source = saved && node.nodeValue === saved.rendered ? saved.source : node.nodeValue;
      const rendered = translate(source, locale);
      if (node.nodeValue !== rendered) node.nodeValue = rendered;
      textMemory.set(node, { source, rendered });
    }
    root.querySelectorAll('[title], [aria-label], [aria-valuetext]').forEach(element => {
      if (element.closest('[data-no-translate]')) return;
      const memory = attributeMemory.get(element) || {};
      for (const attribute of attributes) {
        const current = element.getAttribute(attribute);
        if (current === null) continue;
        const saved = memory[attribute];
        const source = saved && current === saved.rendered ? saved.source : current;
        const rendered = translate(source, locale);
        if (current !== rendered) element.setAttribute(attribute, rendered);
        memory[attribute] = { source, rendered };
      }
      attributeMemory.set(element, memory);
    });
    root.documentElement.lang = locale;
    observer.observe(root.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributes });
  }
  root.querySelectorAll('[data-locale]').forEach(button => button.addEventListener('click', () => {
    locale = button.dataset.locale;
    root.querySelectorAll('[data-locale]').forEach(b => b.setAttribute('aria-pressed', String(b === button)));
    apply();
  }));
  apply();
  return { apply, getLocale: () => locale };
}
